// One-off generator: reads the real Utopia <-> Aquamarine route data from the city_drive_one game
// and writes src/route/route-data.ts (local metres). Usage: node scripts/extract-route.mjs path/to/city_drive_one/index.html
import { readFile, writeFile } from 'node:fs/promises';

const file = process.argv[2];
if (!file) { console.error('usage: node scripts/extract-route.mjs <city_drive_one/index.html>'); process.exit(1); }
const text = await readFile(file, 'utf8');
const routes = JSON.parse(text.match(/var ROUTES_RAW=(\[\[[\s\S]*?\]\]);/)[1]);
const miles = JSON.parse(text.match(/var MILES=(\[[\s\S]*?\]);/)[1]);
const names = JSON.parse(text.match(/var ROUTE_NAMES=(\[.*?\]);/)[1]);

const LON0 = 77.72, LAT0 = 12.955, K = 111320, C = Math.cos((LAT0 * Math.PI) / 180);
// x = east, z = -north so that x,y(up),z is right-handed in three.js
const proj = (lon, lat) => [Math.round((lon - LON0) * K * C * 10) / 10, Math.round(-(lat - LAT0) * K * 10) / 10];
const line = (flat) => { const o = []; for (let i = 0; i < flat.length; i += 2) o.push(proj(flat[i], flat[i + 1])); return o; };

const out = `// GENERATED by scripts/extract-route.mjs from city_drive_one (real Mapbox centrelines). Do not edit.
// Local metres: x = east, z = -north, origin at lon ${LON0}, lat ${LAT0}.
export const ROUTE_NAMES = ${JSON.stringify(names)} as const;
export const ROUTE_A: readonly (readonly [number, number])[] = ${JSON.stringify(line(routes[0]))};
export const ROUTE_B: readonly (readonly [number, number])[] = ${JSON.stringify(line(routes[1]))};
export const MILESTONES: readonly { id: string; name: string; short: string; x: number; z: number }[] = ${JSON.stringify(miles.map(m => { const [x, z] = proj(m.lon, m.lat); return { id: m.id, name: m.name, short: m.short, x, z }; }))};
`;
await writeFile('src/route/route-data.ts', out);
console.log('wrote src/route/route-data.ts', (out.length / 1024).toFixed(0), 'KB');
